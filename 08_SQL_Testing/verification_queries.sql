-- 1) ดูคำสั่งซื้อทั้งหมดคร่าวๆ
SELECT * FROM orders;

-- 2) ตรวจว่าชื่อลูกค้า เบอร์โทร ยอดเงิน บันทึกถูกต้องหรือไม่
--    เทียบผลลัพธ์กับที่กรอกบนหน้าเว็บ (เช่น TC-001: 0812345678 / 135.00)
SELECT customer_name, phone, total_amount
FROM orders
WHERE order_id = 1;

-- 3) หาเบอร์โทรที่ผิดรูปแบบ (ผลลัพธ์ที่ดีต้องเป็น 0 แถว)
--    GLOB '0[0-9][0-9]...' = ขึ้นต้น 0 ตามด้วย "ตัวเลข 0-9" อีก 9 ตัวเท่านั้น
--    หมายเหตุ: ห้ามใช้ LIKE '0_________' เพราะ _ ตรงกับตัวอักษรอะไรก็ได้
--    ทำให้เบอร์แบบ '081234abcd' หลุดการตรวจ (พบจากการทดสอบจริง)
SELECT order_id, phone
FROM orders
WHERE phone NOT GLOB '0[0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9][0-9]';

--    (MySQL ใช้: WHERE phone NOT REGEXP '^0[0-9]{9}$')

-- 4) หาคำสั่งซื้อที่ยอดต่ำกว่าขั้นต่ำ 100 บาท หรือติดลบ
--    (ผลลัพธ์ที่ดีต้องเป็น 0 แถว — ถ้ามี = บั๊กประเภท BUG-002 หลุดเข้ามา)
SELECT order_id, total_amount
FROM orders
WHERE total_amount < 100;
